//! The Rust-source emitter: a wgpu-free [`Reflection`] → the text of the renderer's committed
//! `shader_gen.rs` (Plan/shader-bindgen.md Wave 3).
//!
//! Output is deterministic and byte-stable (decision 7): the header names the reflected source files
//! in sorted order, and structs/consts follow the reflection's sorted order with fields in
//! memory-offset order. The emitter targets rustfmt-clean and clippy-clean-under-`-D warnings` output
//! as written — no post-formatting pass — so the drift gate can byte-compare against the committed
//! file. Baked `const _: () = assert!(…)` size/offset checks travel with each struct, so a layout
//! slip is a compile error at the use site, not a corrupted pixel.
//!
//! Emitted, in order: hoisted scalar consts, buffer-backed structs (with synthesized `_padN` byte
//! fields wherever the layout has a gap, so the POD is `Pod`-safe and the offsets hold),
//! binding-index consts + BGL descriptors, reflected vertex-input lists, and compute workgroup sizes.
//! A bind group whose every member is compute-only and holds a texture or sampler gets its binding
//! consts but no BGL: compute pipelines bind through auto-derived layouts (per-entry-point subsets,
//! use-derived texture filterability) that one unified BGL cannot express. A compute-only group of
//! buffers only has no such ambiguity and gets its BGL, so several entry points can share one bind
//! group. The [`Emitter`] is a plain line accumulator,
//! so a new section slots in without restructuring.

use crate::model::{
    BindGroupLayout, BindingKind, BindingResource, BufferSpace, Reflection, ScalarConst,
    ScalarKind, ShaderStage, StorageAccess, StorageFormat, StructLayout, TextureDim, TextureSample,
    TypeRef, VertexFormat,
};

/// Emit the full contents of the renderer's `shader_gen.rs` from a reflection.
pub fn emit(reflection: &Reflection) -> String {
    let mut e = Emitter { out: String::new() };
    e.header(reflection);
    for c in &reflection.consts {
        e.scalar_const(c);
    }
    for s in &reflection.structs {
        e.struct_pod(s);
    }
    e.binding_indices(reflection);
    for g in &reflection.bind_groups {
        // Compute pipelines keep their auto-derived layouts (see the module docs), so a compute-only
        // group with a non-buffer member has no BGL to generate.
        let compute_only = g.members.iter().all(|m| {
            reflection
                .binding_named(m)
                .is_some_and(|b| b.visibility == [ShaderStage::Compute])
        });
        let all_buffers = g.members.iter().all(|m| {
            reflection
                .binding_named(m)
                .is_some_and(|b| matches!(b.kind, BindingKind::Buffer { .. }))
        });
        if !compute_only || all_buffers {
            e.bind_group_layout(reflection, g);
        }
    }
    e.vertex_inputs(reflection);
    e.workgroup_sizes(reflection);
    // rustfmt wants exactly one trailing newline; the per-item blank lines leave two.
    format!("{}\n", e.out.trim_end())
}

struct Emitter {
    out: String,
}

impl Emitter {
    fn line(&mut self, s: &str) {
        self.out.push_str(s);
        self.out.push('\n');
    }

    fn blank(&mut self) {
        self.out.push('\n');
    }

    fn header(&mut self, reflection: &Reflection) {
        self.line(
            "// GENERATED by ludion-shader-bindgen — edit the WGSL, then regenerate (cargo run -p ludion-shader-bindgen).",
        );
        self.line(&format!("// Source: {}", reflection.units.join(", ")));
        self.line("//");
        self.line(
            "// The CPU-side mirror of every buffer-backed WGSL uniform/storage struct and hoisted",
        );
        self.line(
            "// const, with memory offsets from naga's Layouter (what `create_shader_module` computes),",
        );
        self.line(
            "// plus binding-index consts, BGL descriptors (visibility + min_binding_size reflected),",
        );
        self.line("// each vertex entry point's reflected `@location` inputs, and each compute entry point's");
        self.line("// `@workgroup_size`.");
        self.line("// Do not edit by hand.");
        self.line("#![allow(dead_code)]");
        self.blank();
        self.line("use bytemuck::{Pod, Zeroable};");
        self.blank();
    }

    fn scalar_const(&mut self, c: &ScalarConst) {
        let ty = rust_scalar(c.kind);
        self.line(&format!(
            "/// `{}`, hoisted from WGSL `const {}: {}`.",
            c.name, c.name, ty
        ));
        self.line("///");
        self.line(&format!("/// Declared in {}.", provenance(&c.units)));
        self.line(&format!("pub const {}: {} = {};", c.name, ty, c.value));
        self.blank();
    }

    fn struct_pod(&mut self, s: &StructLayout) {
        self.line(&format!("/// WGSL `struct {}`.", s.name));
        self.line("///");
        self.line(&format!("/// Declared in {}.", provenance(&s.units)));
        self.line("#[repr(C)]");
        self.line("#[derive(Clone, Copy, Pod, Zeroable)]");
        self.line(&format!("pub struct {} {{", s.name));
        // `cursor` is the end of the previous field: a gap before the next offset (or before the
        // struct's rounded-up size) becomes an explicit byte array so the POD has no implicit padding.
        let mut cursor = 0;
        let mut pads = 0;
        let mut pad_to = |e: &mut Self, cursor: u32, offset: u32| {
            if offset > cursor {
                e.line(&format!("    pub _pad{pads}: [u8; {}],", offset - cursor));
                pads += 1;
            }
        };
        for f in &s.fields {
            pad_to(self, cursor, f.offset);
            self.line(&format!("    pub {}: {},", f.name, rust_type(&f.ty)));
            cursor = f.offset + f.size;
        }
        pad_to(self, cursor, s.size);
        self.line("}");
        self.line(&format!(
            "const _: () = assert!(core::mem::size_of::<{}>() == {});",
            s.name, s.size
        ));
        for f in &s.fields {
            self.line(&format!(
                "const _: () = assert!(core::mem::offset_of!({}, {}) == {});",
                s.name, f.name, f.offset
            ));
        }
        self.blank();
    }

    /// Per-resource `@group`/`@binding` consts, replacing the magic numbers at every bind-group and
    /// `set_bind_group` site (Plan/shader-bindgen.md decision 3). Bindings are already sorted by
    /// `(group, binding, name)`.
    fn binding_indices(&mut self, reflection: &Reflection) {
        if reflection.bindings.is_empty() {
            return;
        }
        self.section("Binding indices (@group / @binding per WGSL resource)");
        for b in &reflection.bindings {
            let up = b.name.to_uppercase();
            self.line(&format!(
                "/// `{}` — `@group({}) @binding({})`, in {}.",
                b.name,
                b.group,
                b.binding,
                provenance(&b.units)
            ));
            self.line(&format!("pub const {up}_GROUP: u32 = {};", b.group));
            self.line(&format!("pub const {up}_BINDING: u32 = {};", b.binding));
            self.blank();
        }
    }

    /// One `create_<name>_bgl` function per unified bind group layout: entries in binding order,
    /// visibility from the merged per-entry-point usage, and `min_binding_size` pinned to the
    /// reflected buffer size (decision 3, the rev-211 lights pin generalized to every buffer entry).
    ///
    /// rustfmt hugs a single-element `entries: &[Entry { … }]` array onto the `&[` line and vertically
    /// stacks a multi-element one; the emitter matches both so its output is fmt-idempotent.
    fn bind_group_layout(&mut self, reflection: &Reflection, g: &BindGroupLayout) {
        let member = |name: &str| {
            reflection
                .binding_named(name)
                .expect("a bind group member is always a reflected binding")
        };
        self.line(&format!(
            "/// Bind group layout `{}` (@group {}), from {}.",
            g.name,
            g.group,
            provenance(&g.units)
        ));
        // rustfmt keeps the signature on one line while it fits `max_width` (100) and otherwise
        // breaks the single `device` param onto its own line; the emitter matches both so its output
        // stays fmt-idempotent for a long unified name (e.g. the IBL group's concatenated members).
        let signature = format!(
            "pub fn create_{}_bgl(device: &wgpu::Device) -> wgpu::BindGroupLayout {{",
            g.name
        );
        if signature.len() > 100 {
            self.line(&format!("pub fn create_{}_bgl(", g.name));
            self.line("    device: &wgpu::Device,");
            self.line(") -> wgpu::BindGroupLayout {");
        } else {
            self.line(&signature);
        }
        self.line("    device.create_bind_group_layout(&wgpu::BindGroupLayoutDescriptor {");
        self.line(&format!("        label: Some({:?}),", g.name));
        if let [only] = g.members.as_slice() {
            self.line("        entries: &[wgpu::BindGroupLayoutEntry {");
            self.entry_fields(member(only), 12);
            self.line("        }],");
        } else {
            self.line("        entries: &[");
            for name in &g.members {
                self.line("            wgpu::BindGroupLayoutEntry {");
                self.entry_fields(member(name), 16);
                self.line("            },");
            }
            self.line("        ],");
        }
        self.line("    })");
        self.line("}");
        self.blank();
    }

    /// The `binding`/`visibility`/`ty`/`count` fields of one entry, indented `ind` spaces (12 for the
    /// hugged single-entry form, 16 for the stacked multi-entry form).
    fn entry_fields(&mut self, b: &BindingResource, ind: usize) {
        let pad = " ".repeat(ind);
        let up = b.name.to_uppercase();
        self.line(&format!("{pad}binding: {up}_BINDING,"));
        self.line(&format!(
            "{pad}visibility: {},",
            visibility_expr(&b.visibility)
        ));
        match &b.kind {
            BindingKind::Buffer {
                address_space,
                min_size,
            } => self.buffer_ty(ind, *address_space, *min_size),
            BindingKind::Texture {
                dim,
                sample,
                multisampled,
            } => self.texture_ty(ind, *dim, *sample, *multisampled),
            BindingKind::StorageTexture {
                dim,
                format,
                access,
            } => self.storage_texture_ty(ind, *dim, *format, *access),
            BindingKind::Sampler { comparison } => self.sampler_ty(ind, *comparison),
        }
        self.line(&format!("{pad}count: None,"));
    }

    fn buffer_ty(&mut self, ind: usize, space: BufferSpace, min_size: u32) {
        let pad = " ".repeat(ind);
        let inner = " ".repeat(ind + 4);
        let ty = match space {
            BufferSpace::Uniform => "wgpu::BufferBindingType::Uniform".to_string(),
            BufferSpace::Storage { read_only } => {
                format!("wgpu::BufferBindingType::Storage {{ read_only: {read_only} }}")
            }
        };
        self.line(&format!("{pad}ty: wgpu::BindingType::Buffer {{"));
        self.line(&format!("{inner}ty: {ty},"));
        self.line(&format!("{inner}has_dynamic_offset: false,"));
        self.line(&format!(
            "{inner}min_binding_size: wgpu::BufferSize::new({min_size}),"
        ));
        self.line(&format!("{pad}}},"));
    }

    fn texture_ty(
        &mut self,
        ind: usize,
        dim: TextureDim,
        sample: TextureSample,
        multisampled: bool,
    ) {
        let pad = " ".repeat(ind);
        let inner = " ".repeat(ind + 4);
        self.line(&format!("{pad}ty: wgpu::BindingType::Texture {{"));
        self.line(&format!(
            "{inner}sample_type: {},",
            texture_sample_expr(sample)
        ));
        self.line(&format!(
            "{inner}view_dimension: {},",
            texture_dim_expr(dim)
        ));
        self.line(&format!("{inner}multisampled: {multisampled},"));
        self.line(&format!("{pad}}},"));
    }

    fn storage_texture_ty(
        &mut self,
        ind: usize,
        dim: TextureDim,
        format: StorageFormat,
        access: StorageAccess,
    ) {
        let pad = " ".repeat(ind);
        let inner = " ".repeat(ind + 4);
        self.line(&format!("{pad}ty: wgpu::BindingType::StorageTexture {{"));
        self.line(&format!("{inner}access: {},", storage_access_expr(access)));
        self.line(&format!("{inner}format: {},", storage_format_expr(format)));
        self.line(&format!(
            "{inner}view_dimension: {},",
            texture_dim_expr(dim)
        ));
        self.line(&format!("{pad}}},"));
    }

    fn sampler_ty(&mut self, ind: usize, comparison: bool) {
        let pad = " ".repeat(ind);
        let binding = if comparison {
            "wgpu::SamplerBindingType::Comparison"
        } else {
            "wgpu::SamplerBindingType::Filtering"
        };
        self.line(&format!("{pad}ty: wgpu::BindingType::Sampler({binding}),"));
    }

    /// Reflected `@location` vertex inputs per vertex entry point, as `(location, format)` data. A
    /// hand-written renderer test compares these against the pipelines' `vertex_attr_array!` literals
    /// (decision 3): the data is generated from the WGSL, the comparison is hand-owned.
    fn vertex_inputs(&mut self, reflection: &Reflection) {
        let with_inputs: Vec<_> = reflection
            .entry_points
            .iter()
            .filter(|e| e.stage == ShaderStage::Vertex && !e.inputs.is_empty())
            .collect();
        if with_inputs.is_empty() {
            return;
        }
        self.section("Vertex inputs (reflected @location/format per vertex entry point)");
        for ep in with_inputs {
            let ident = format!("{}_{}_INPUTS", unit_ident(&ep.unit), ep.name.to_uppercase());
            self.line(&format!(
                "/// `{}`'s `{}` `@location` inputs, in location order.",
                ep.unit, ep.name
            ));
            self.line(&format!(
                "pub const {ident}: &[(u32, wgpu::VertexFormat)] = &["
            ));
            for i in &ep.inputs {
                self.line(&format!(
                    "    ({}, {}),",
                    i.location,
                    vertex_format_expr(i.format)
                ));
            }
            self.line("];");
            self.blank();
        }
    }

    /// Each compute entry point's declared `@workgroup_size`, so a CPU dispatch divides by the
    /// shader's own tile instead of a hand-copied constant.
    fn workgroup_sizes(&mut self, reflection: &Reflection) {
        let computes: Vec<_> = reflection
            .entry_points
            .iter()
            .filter(|e| e.stage == ShaderStage::Compute)
            .collect();
        if computes.is_empty() {
            return;
        }
        self.section("Compute workgroup sizes (@workgroup_size per compute entry point)");
        for ep in computes {
            let ident = format!(
                "{}_{}_WORKGROUP_SIZE",
                unit_ident(&ep.unit),
                ep.name.to_uppercase()
            );
            let [x, y, z] = ep.workgroup_size;
            self.line(&format!(
                "/// `{}`'s `{}` `@workgroup_size`.",
                ep.unit, ep.name
            ));
            self.line(&format!("pub const {ident}: [u32; 3] = [{x}, {y}, {z}];"));
            self.blank();
        }
    }

    /// A `// --- <title> ---` section banner, padded to the emitter's 100-column comment width.
    fn section(&mut self, title: &str) {
        let prefix = format!("// --- {title} ");
        let dashes = 100usize.saturating_sub(prefix.len());
        self.line(&format!("{prefix}{}", "-".repeat(dashes)));
        self.blank();
    }
}

/// The `wgpu::ShaderStages` expression for a merged visibility set.
fn visibility_expr(stages: &[ShaderStage]) -> String {
    let one = |s: ShaderStage| match s {
        ShaderStage::Vertex => "wgpu::ShaderStages::VERTEX",
        ShaderStage::Fragment => "wgpu::ShaderStages::FRAGMENT",
        ShaderStage::Compute => "wgpu::ShaderStages::COMPUTE",
    };
    match stages {
        [ShaderStage::Vertex, ShaderStage::Fragment] => {
            "wgpu::ShaderStages::VERTEX_FRAGMENT".to_string()
        }
        [only] => one(*only).to_string(),
        [] => "wgpu::ShaderStages::empty()".to_string(),
        many => many.iter().map(|s| one(*s)).collect::<Vec<_>>().join(" | "),
    }
}

fn texture_sample_expr(sample: TextureSample) -> String {
    match sample {
        TextureSample::Float { filterable } => {
            format!("wgpu::TextureSampleType::Float {{ filterable: {filterable} }}")
        }
        TextureSample::Depth => "wgpu::TextureSampleType::Depth".to_string(),
        TextureSample::Sint => "wgpu::TextureSampleType::Sint".to_string(),
        TextureSample::Uint => "wgpu::TextureSampleType::Uint".to_string(),
    }
}

fn texture_dim_expr(dim: TextureDim) -> &'static str {
    match dim {
        TextureDim::D1 => "wgpu::TextureViewDimension::D1",
        TextureDim::D2 => "wgpu::TextureViewDimension::D2",
        TextureDim::D3 => "wgpu::TextureViewDimension::D3",
        TextureDim::Cube => "wgpu::TextureViewDimension::Cube",
        TextureDim::D2Array => "wgpu::TextureViewDimension::D2Array",
        TextureDim::CubeArray => "wgpu::TextureViewDimension::CubeArray",
    }
}

fn storage_access_expr(access: StorageAccess) -> &'static str {
    match access {
        StorageAccess::ReadOnly => "wgpu::StorageTextureAccess::ReadOnly",
        StorageAccess::WriteOnly => "wgpu::StorageTextureAccess::WriteOnly",
        StorageAccess::ReadWrite => "wgpu::StorageTextureAccess::ReadWrite",
    }
}

fn storage_format_expr(format: StorageFormat) -> &'static str {
    match format {
        StorageFormat::Rgba8Unorm => "wgpu::TextureFormat::Rgba8Unorm",
        StorageFormat::Rgba16Float => "wgpu::TextureFormat::Rgba16Float",
        StorageFormat::Rgba32Float => "wgpu::TextureFormat::Rgba32Float",
        StorageFormat::R32Float => "wgpu::TextureFormat::R32Float",
        StorageFormat::R32Uint => "wgpu::TextureFormat::R32Uint",
        StorageFormat::R32Sint => "wgpu::TextureFormat::R32Sint",
        StorageFormat::Rg32Float => "wgpu::TextureFormat::Rg32Float",
    }
}

fn vertex_format_expr(format: VertexFormat) -> &'static str {
    match format {
        VertexFormat::Float32 => "wgpu::VertexFormat::Float32",
        VertexFormat::Float32x2 => "wgpu::VertexFormat::Float32x2",
        VertexFormat::Float32x3 => "wgpu::VertexFormat::Float32x3",
        VertexFormat::Float32x4 => "wgpu::VertexFormat::Float32x4",
        VertexFormat::Sint32 => "wgpu::VertexFormat::Sint32",
        VertexFormat::Sint32x2 => "wgpu::VertexFormat::Sint32x2",
        VertexFormat::Sint32x3 => "wgpu::VertexFormat::Sint32x3",
        VertexFormat::Sint32x4 => "wgpu::VertexFormat::Sint32x4",
        VertexFormat::Uint32 => "wgpu::VertexFormat::Uint32",
        VertexFormat::Uint32x2 => "wgpu::VertexFormat::Uint32x2",
        VertexFormat::Uint32x3 => "wgpu::VertexFormat::Uint32x3",
        VertexFormat::Uint32x4 => "wgpu::VertexFormat::Uint32x4",
    }
}

/// The uppercase identifier prefix for a unit name (`ui_rect.wgsl` → `UI_RECT`).
fn unit_ident(unit: &str) -> String {
    unit.strip_suffix(".wgsl")
        .unwrap_or(unit)
        .to_uppercase()
        .replace(|c: char| !c.is_ascii_alphanumeric(), "_")
}

/// `` `a.wgsl`, `b.wgsl` `` — the provenance file list for a doc comment.
fn provenance(units: &[String]) -> String {
    units
        .iter()
        .map(|u| format!("`{u}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

fn rust_scalar(kind: ScalarKind) -> &'static str {
    match kind {
        ScalarKind::F16 => "f16",
        ScalarKind::F32 => "f32",
        ScalarKind::F64 => "f64",
        ScalarKind::I32 => "i32",
        ScalarKind::U32 => "u32",
        ScalarKind::I64 => "i64",
        ScalarKind::U64 => "u64",
        ScalarKind::Bool => "bool",
    }
}

/// The Rust POD spelling of a reflected type. Vectors/matrices become fixed arrays whose byte size
/// matches the WGSL layout — the baked size/offset asserts catch any mismatch at compile time.
/// A three-row matrix column and a three-component array element each occupy 16 bytes in WGSL, so
/// they spell four lanes: the fourth is WGSL's padding.
fn rust_type(ty: &TypeRef) -> String {
    match ty {
        TypeRef::Scalar(k) | TypeRef::Atomic(k) => rust_scalar(*k).to_string(),
        TypeRef::Vector { components, scalar } => {
            format!("[{}; {}]", rust_scalar(*scalar), components)
        }
        TypeRef::Matrix {
            columns,
            rows,
            scalar,
        } => {
            let lanes = if *rows == 3 { 4 } else { *rows };
            format!("[[{}; {}]; {}]", rust_scalar(*scalar), lanes, columns)
        }
        TypeRef::Array { element, count, .. } => {
            let n = count
                .expect("reflection rejects a runtime-sized struct member before it reaches emit");
            match element.as_ref() {
                TypeRef::Vector {
                    components: 3,
                    scalar,
                } => format!("[[{}; 4]; {}]", rust_scalar(*scalar), n),
                element => format!("[{}; {}]", rust_type(element), n),
            }
        }
        TypeRef::Struct(name) => name.clone(),
    }
}
