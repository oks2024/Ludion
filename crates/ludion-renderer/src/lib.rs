//! `ludion-renderer` — the engine's rendering pipeline on wgpu.
//!
//! The renderer consumes exactly one thing: a [`RenderScene`] (plain data — camera, meshes, sprites,
//! lights, text, decoded textures; no ECS, no asset paths). `ludion-engine`'s `extract()` produces
//! it; this crate uploads it and draws it, so `ludion-renderer` depends on **neither `ludion-ecs` nor
//! `ludion-scene`** (boundary rule, `engine-architecture.md` §2). It builds ON `ludion-render-graph`:
//! the [`build_frame_graph`] frame graph declares the passes (all `PassKind::External`), the graph
//! owns scheduling / transient aliasing / the JSON dump, and the renderer records the GPU work
//! through the graph's [`PassRecorder`](ludion_render_graph::PassRecorder) seam.
//!
//! # The pipeline
//!
//! A fixed five-pass graph (see [`crate::graph`]): an HDR **scene** pass (faceted meshes with
//! dynamic point lights, then lit alpha-blended sprites/billboards, then bitmap text), a modest
//! **bloom** (bright-pass + separable blur at half resolution), and a **composite** pass (exposure,
//! a selectable tonemap operator, optional output dither; HDR→sRGB) into the read-back target.
//! Conditional passes ([`PostChain`]) extend it. No temporal
//! accumulation — test mode is the only mode. Determinism: the same scene on the same adapter yields
//! byte-identical pixels, across processes.
//!
//! # Example — build and dump the graph with no GPU
//!
//! ```
//! use ludion_renderer::{FrameSize, PostChain};
//!
//! let size = FrameSize::native(1280, 720);
//! let json = ludion_renderer::dump_frame_graph_json(size, PostChain::default()).unwrap();
//! assert!(json.contains("\"composite\""));
//! ```
//!
//! # Example — render a scene (requires a GPU adapter)
//!
//! ```no_run
//! use ludion_renderer::{FrameSize, RenderScene, Renderer};
//! let renderer = Renderer::new()?;
//! let scene = RenderScene::empty((1280, 720));
//! let image = renderer.render(&scene, FrameSize::native(1280, 720))?;
//! image.write_png("frame.png")?;
//! # Ok::<(), ludion_core::diagnostics::Diagnostic>(())
//! ```

