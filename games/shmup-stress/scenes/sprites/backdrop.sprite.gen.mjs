// The stress arena's backdrop tileset: four 40x40 tiles the scrolling `Tilemap` lays down behind the
// bullet field. Forty texels a side is the atlas's own density (`pixels_per_unit: 40`), so a
// `cell_size: 1.0` cell covers exactly one region with no stretch and the grid tiles seamlessly.
//
// Generated for the same reason the bullet sheet is: 160 rows of glyphs carry no meaning a loop does
// not. The shapes are flat glyph fields; the grain comes from the doc-level `noise` op.
//
// Regenerate with, from the workspace root:
//   node games/shmup-stress/scenes/sprites/backdrop.sprite.gen.mjs games/shmup-stress/scenes/sprites/backdrop.sprite.yaml
// then re-bake the atlas: `cargo run -p ludion-cli -- generate-atlas games/shmup-stress/scenes/sprites/shmup.atlas-source.yaml`

import { writeFileAtomic } from '../../../../scripts/atomic-write.mjs';

const SIZE = 40;

// `p` plate, `q` a lighter plate, `l` the grid rule, `s` a star.
const PALETTE = [
  ['p', '#353848'],
  ['q', '#424657'],
  ['l', '#59657c'],
  ['s', '#c4cbe1'],
];

// A fixed, seedless speckle: the plate's lighter flecks are a function of the texel coordinate, so
// the tileset bakes identically on any machine without needing the RNG the format reserves for
// `noise`.
const fleck = (x, y) => (x * 7 + y * 13) % 23 === 0;

const TILES = {
  // The plain plate, and the three variations the scene's glyph grid mixes into it.
  t0: (x, y) => (fleck(x, y) ? 'q' : 'p'),
  // A rule along the top and left edges: laid on a grid these meet as one continuous lattice.
  t1: (x, y) => (x === 0 || y === 0 ? 'l' : fleck(x, y) ? 'q' : 'p'),
  // Four stars at fixed offsets.
  t2: (x, y) => {
    const stars = [
      [7, 9],
      [21, 6],
      [13, 28],
      [31, 22],
    ];
    if (stars.some(([sx, sy]) => sx === x && sy === y)) return 's';
    return fleck(x, y) ? 'q' : 'p';
  },
  // An inset panel: a lighter plate inside a ruled border.
  t3: (x, y) => {
    const inset = x >= 6 && x < SIZE - 6 && y >= 6 && y < SIZE - 6;
    const border = inset && (x === 6 || x === SIZE - 7 || y === 6 || y === SIZE - 7);
    if (border) return 'l';
    if (inset) return 'q';
    return fleck(x, y) ? 'q' : 'p';
  },
};

const out = [];
out.push('# The stress arena backdrop tileset: four 40x40 tiles for the scrolling Tilemap.');
out.push('# GENERATED by backdrop.sprite.gen.mjs — do not hand-edit; regenerate and re-bake the atlas.');
out.push('# Every frame is edge-to-edge opaque so the grid has no gaps.');
out.push('format: 1');
out.push('kind: sprite');
out.push('name: backdrop');
out.push('size:');
out.push(`  - ${SIZE}`);
out.push(`  - ${SIZE}`);
out.push('seed: 20260912');
out.push('palette:');
for (const [glyph, hex] of PALETTE) {
  out.push(`  ${glyph}:`);
  out.push(`    color: "${hex}"`);
}
out.push('frames:');
for (const [name, tile] of Object.entries(TILES)) {
  out.push(`  ${name}:`);
  out.push('    rows:');
  for (let y = 0; y < SIZE; y += 1) {
    let row = '';
    for (let x = 0; x < SIZE; x += 1) row += tile(x, y);
    out.push(`      - "${row}"`);
  }
}
out.push('effects:');
out.push('  - op: noise');
out.push('    amount: 0.025');

const dest = process.argv[2];
if (!dest) throw new Error('usage: node backdrop.sprite.gen.mjs <out.sprite.yaml>');
writeFileAtomic(dest, `${out.join('\n')}\n`);
