// The stress arena's bullet sheet: forty 12x12 frames, five silhouettes in eight hues, written as a
// `kind: sprite` document. Generated rather than hand-authored because the only thing that matters
// about the forty is that they are forty *distinct regions* of one atlas — the sprite layer's Wave 4
// exit line (`Plan/sprite-engine.md`) — and a hand-written 480-row grid would carry no more meaning
// than this loop.
//
// Frame `bNN` is silhouette `floor(NN / 8)` in hue `NN % 8`, so the eight hues cycle fastest and any
// run of consecutive spawn ordinals (which is how `emit_bullets` assigns them) draws eight different
// colours before it repeats a shape.
//
// Nothing here paints shading: every shape is a flat glyph field, and the volume and the dark rim
// come from the doc-level `effects:` list, which is the sprite format's rule
// (`ludion docs sprite-effects`). Each shape stays inside the middle 10x10 so the `outline` op has a
// transparent margin to paint into.
//
// Regenerate with, from the workspace root:
//   node games/shmup-stress/scenes/sprites/bullets.sprite.gen.mjs games/shmup-stress/scenes/sprites/bullets.sprite.yaml
// then re-bake the atlas: `cargo run -p ludion-cli -- generate-atlas games/shmup-stress/scenes/sprites/shmup.atlas-source.yaml`

import { writeFileAtomic } from '../../../../scripts/atomic-write.mjs';

const SIZE = 12;
const HUES = [
  ['A', [0.9, 0.1, 0.14]],
  ['B', [0.95, 0.38, 0.06]],
  ['C', [0.95, 0.82, 0.1]],
  ['D', [0.22, 0.8, 0.26]],
  ['E', [0.1, 0.78, 0.88]],
  ['F', [0.16, 0.36, 0.95]],
  ['G', [0.55, 0.26, 0.92]],
  ['H', [0.93, 0.2, 0.66]],
];

// The five silhouettes, as predicates over the texel's offset from the frame centre. `dx`/`dy` are
// measured from the centre of the 12x12 grid, so a texel at column 0 sits at -5.5 and is outside
// every shape — the margin the outline needs.
const SHAPES = [
  (dx, dy) => dx * dx + dy * dy <= 21.16, // disc
  (dx, dy) => dx * dx + dy * dy <= 21.16 && dx * dx + dy * dy >= 7.29, // ring
  (dx, dy) => Math.abs(dx) + Math.abs(dy) <= 5.0, // diamond
  (dx, dy) =>
    Math.abs(dx) + Math.abs(dy) <= 5.4 && (Math.abs(dx) <= 1.6 || Math.abs(dy) <= 1.6), // star
  (dx, dy) => dx * dx + dy * dy <= 9.0, // pip
];

function frameRows(shape, glyph) {
  const rows = [];
  for (let y = 0; y < SIZE; y += 1) {
    let row = '';
    for (let x = 0; x < SIZE; x += 1) {
      row += shape(x - (SIZE - 1) / 2, y - (SIZE - 1) / 2) ? glyph : '.';
    }
    rows.push(row);
  }
  return rows;
}

const out = [];
out.push('# The stress arena bullet sheet: forty 12x12 frames, five silhouettes in eight hues.');
out.push('# GENERATED by bullets.sprite.gen.mjs — do not hand-edit; regenerate and re-bake the atlas.');
out.push('# At 40 texels to the unit a 12-texel frame derives exactly the 0.3 u quad the arena');
out.push('# spawns a flat bullet at, so a drawn bullet is the same square an undrawn one is.');
out.push('format: 1');
out.push('kind: sprite');
out.push('name: bullets');
out.push('size:');
out.push(`  - ${SIZE}`);
out.push(`  - ${SIZE}`);
out.push('seed: 20260912');
out.push('palette:');
for (const [glyph, [r, g, b]] of HUES) {
  out.push(`  ${glyph}:`);
  out.push('    color:');
  for (const c of [r, g, b, 1.0]) out.push(`      - ${c.toFixed(3)}`);
}
out.push('frames:');
for (let k = 0; k < SHAPES.length * HUES.length; k += 1) {
  const [glyph] = HUES[k % HUES.length];
  const shape = SHAPES[Math.floor(k / HUES.length)];
  out.push(`  b${String(k).padStart(2, '0')}:`);
  out.push('    rows:');
  for (const row of frameRows(shape, glyph)) out.push(`      - "${row}"`);
}
out.push('effects:');
out.push('  - op: shade');
out.push('    light:');
out.push('      - -1.0');
out.push('      - -1.0');
out.push('    strength: 0.4');
out.push('  - op: outline');
out.push('    color:');
out.push('      - 0.010');
out.push('      - 0.008');
out.push('      - 0.020');
out.push('      - 0.850');
out.push('    side: outside');

const dest = process.argv[2];
if (!dest) throw new Error('usage: node bullets.sprite.gen.mjs <out.sprite.yaml>');
writeFileAtomic(dest, `${out.join('\n')}\n`);
