#!/usr/bin/env node
// Map-authoring drift gate.
//
// The map part is `ludion map-drift` (`ludion docs map-authoring`, "Drift check"): one implementation,
// called once over the scan roots. This script adds the engine-repo-only parts below.
//
// Node generators are sources too: every `.mjs` under the scan roots carrying the line
// `// ludion: drift-generator` is run with `--check` once, unconditionally; the script prints a
// `verified <absolute path>` line for every file it compared, and the same pairing applies to those
// paths (a verified scene that lost its `generated_from:` fails). A script that succeeds without
// printing one is an error, and a scene naming an unmarked `.mjs` is an error.
// A scene generated by a Rust test (`.rs`) is gated by that test's byte compare under `cargo test`;
// the gate only requires the named test file to exist and to mention the scene's file name.
//
// Cheap by construction: a file scan of `games/` and `examples/` only, not a whole-repo walk; each
// scene is read only as far as its leading column-0 keys. Nothing is written.
//
// Run standalone (`node scripts/map-drift.mjs`) or via the `map-drift` step in scripts/check.mjs;
// mirrored as the `map-drift` step in .github/workflows/ci.yml and ci/teamcity/provision.mjs — keep
// the three in step.

import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { DRIFT_GENERATOR_MARKER, REPO_ROOT, SCAN_ROOTS, emptyScan, headGeneratedFrom, isDriftGenerator, pairOutputs, walkFiles } from './drift-lib.mjs';
import { runLudion } from './ludion-bin.mjs';

// Scene documents that may carry a `generated_from:` this gate owns. The derived kinds below name
// their own sources and are gated elsewhere.
const EXCLUDED_SUFFIXES = [
  '.voxel.yaml', // names a generator script, gated by scripts/voxel-drift.mjs
  '.atlas.yaml', // names its atlas-source, gated by scripts/atlas-drift.mjs
  '.font.yaml', // names its font-source, gated by scripts/atlas-drift.mjs
  '.mesh.yaml', // names its mesh-edit, gated by scripts/mesh-edit-drift.mjs
  '.anim.yaml', // names its glTF, gated by the clip drift test in crates/ludion-cli/tests/import.rs
  '.map.yaml', // a source, not a scene
  '.path.yaml', // provenance only: a bpy script is not an engine derive, so nothing to gate
];

const isScene = (name) => {
  if (EXCLUDED_SUFFIXES.some((s) => name.endsWith(s))) return false;
  // An imported `.prefab.yaml` names its glTF (gated by crates/ludion-cli/tests/import.rs); one
  // generated by a script is gated here like a scene — filtered by `generated_from` below.
  return name.endsWith('.yaml') || name.endsWith('.yml');
};

// The verb's `--json` report as gate errors; a dead or unreadable verb is one error.
function mapErrors(run) {
  let report = null;
  try {
    report = JSON.parse(run.stdout ?? '');
  } catch {}
  const dead = () => [`map-drift: \`ludion map-drift\` failed:\n${run.error?.message || (run.stderr || run.stdout || '').trim() || `exit ${run.status}`}`];
  if (run.error || !Array.isArray(report?.files)) return { errors: dead(), outputs: 0 };
  const errors = [];
  for (const { file, diagnostics } of report.files) {
    for (const d of diagnostics ?? []) {
      if (d.severity === 'warning') continue;
      errors.push(`${file}: [${d.code}] ${d.message}${d.help ? `\n  help: ${d.help}` : ''}`);
    }
  }
  if (run.status !== 0 && errors.length === 0) errors.push(...dead());
  return { errors, outputs: report.outputs ?? 0 };
}

export function runGate({ root = REPO_ROOT, scanRoots = SCAN_ROOTS, ludion = runLudion } = {}) {
  const rel = (p) => path.relative(root, p).replaceAll('\\', '/');
  const errors = [];
  const verified = new Map();
  const maps = walkFiles(root, scanRoots, (name) => name.endsWith('.map.yaml'));
  const claims = [];
  const generators = new Map(); // absolute generator -> verified paths, or null once it failed
  const scripts = walkFiles(root, scanRoots, (name) => name.endsWith('.mjs')).filter(isDriftGenerator);
  if (maps.length + scripts.length === 0) {
    errors.push(emptyScan('map-drift', `map sources (*.map.yaml) or marked generators (\`${DRIFT_GENERATOR_MARKER}\`)`, scanRoots));
  }

  let outputs = 0;
  if (maps.length > 0) {
    const result = mapErrors(ludion(['map-drift', '--root', root, '--json', ...scanRoots], { cwd: root }));
    errors.push(...result.errors);
    outputs = result.outputs;
  }

  for (const script of scripts) {
    const run = spawnSync(process.execPath, [script, '--check'], { cwd: root, encoding: 'utf8' });
    if (run.status !== 0) {
      generators.set(script, null);
      errors.push(`${rel(script)}: \`node ${rel(script)} --check\` failed:\n${(run.stderr || run.stdout || `exit ${run.status}`).trim()}`);
      continue;
    }
    const paths = [...(run.stdout ?? '').matchAll(/^verified (.+?)\s*$/gm)].map((m) => path.resolve(root, m[1]));
    if (paths.length === 0) {
      generators.set(script, null);
      errors.push(`${rel(script)}: \`--check\` succeeded but printed no verified path`);
      continue;
    }
    generators.set(script, paths);
    verified.set(script, paths);
  }
  const scriptChecked = scripts.length;
  let rsChecked = 0;
  for (const scene of walkFiles(root, scanRoots, isScene)) {
    const source = headGeneratedFrom(scene);
    if (!source) continue;
    if (source.split(/\s+/)[0].endsWith('.map.yaml')) continue; // `ludion map-drift` owns it, plain or override
    const isPrefab = scene.endsWith('.prefab.yaml');
    if (isPrefab && !source.endsWith('.mjs')) continue;
    const sourcePath = path.resolve(path.dirname(scene), source);

    if (source.endsWith('.rs')) {
      rsChecked += 1;
      if (!existsSync(sourcePath)) {
        errors.push(`${rel(scene)}: names generator \`${source}\`, which does not exist beside it`);
      } else if (!readFileSync(sourcePath, 'utf8').includes(path.basename(scene))) {
        errors.push(
          `${rel(scene)}: names generator \`${source}\`, which never mentions \`${path.basename(scene)}\` — ` +
            'nothing there byte-compares this scene',
        );
      }
      continue;
    }

    if (source.endsWith('.mjs')) {
      if (!existsSync(sourcePath)) {
        errors.push(`${rel(scene)}: names generator \`${source}\`, which does not exist beside it`);
        continue;
      }
      if (!generators.has(sourcePath)) {
        errors.push(
          `${rel(scene)}: names generator \`${source}\`, which is not gated — add the line \`${DRIFT_GENERATOR_MARKER}\` near its top ` +
            'and make its `--check` print `verified <path>` for each file it compares',
        );
        continue;
      }
      if (generators.get(sourcePath)) claims.push({ output: scene, source: sourcePath });
      continue;
    }

    errors.push(
      `${rel(scene)} names ${source} under generated_from, which is not a map source, a .mjs generator or a Rust test`,
    );
  }
  errors.push(...pairOutputs({ root, verified, claims }));
  return { errors, checked: maps.length, scriptChecked, rsChecked, outputs };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { errors, checked, scriptChecked, rsChecked, outputs } = runGate();
  if (errors.length > 0) {
    console.error('MAP DRIFT: committed generated scenes no longer match their map source.\n');
    for (const d of errors) console.error(`  ${d}`);
    console.error('\nRegenerate each with `ludion generate-map <map>` (or `node <generator>` for a script source) and commit the result.');
    process.exit(1);
  }
  console.log(
    `map-drift: ${checked} map(s), ${scriptChecked} script generator(s), ${outputs} map output(s) and ${rsChecked} Rust-generated scene(s) checked, none drifted.`,
  );
}
