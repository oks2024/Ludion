const entry = (e) => `    { path = "${e.path}", reason = "${e.reason}" },`;

// The generated body of a strict/sim `clippy.toml`: one array per key, entries in group order.
export function render(tier) {
  const byKey = new Map();
  for (const name of TIERS[tier]) {
    const { key, entries } = GROUPS[name];
    byKey.set(key, [...(byKey.get(key) ?? []), ...entries]);
  }
  return `${[...byKey].map(([key, entries]) => `${key} = [\n${entries.map(entry).join('\n')}\n]`).join('\n\n')}\n`;
}

const clippyPath = (root, dir) => path.join(root, dir, 'clippy.toml');
const readLf = (p) => readFileSync(p, 'utf8');

// The hand-written part of a file: everything before the marker, or before the first list on the
// first run.
function headerOf(content) {
  const at = [MARKER, TEMPLATE_MARKER].map((m) => content.indexOf(m)).find((i) => i >= 0);
  if (at !== undefined) return content.slice(0, at);
  const first = content.search(/^disallowed-(types|methods)\b/m);
  return `${(first >= 0 ? content.slice(0, first) : content).trimEnd()}\n\n`;
}

const expected = (content, tier, marker) => `${headerOf(content)}${marker}\n\n${render(tier)}`;

const FIX = 'run `node scripts/clippy-denylist.mjs --write`';

// The repo-relative dir of every workspace member (`crates/*`, `games/*` with a manifest).
export function workspaceDirs(root) {
  return ['crates', 'games'].flatMap((group) => {
    const dir = path.join(root, group);
    if (!existsSync(dir)) return [];
    return readdirSync(dir)
      .filter((n) => statSync(path.join(dir, n)).isDirectory() && existsSync(path.join(dir, n, 'Cargo.toml')))
      .map((n) => `${group}/${n}`);
  });
}

// `{ errors, count }`: `workspaceDirs` are the repo-relative dirs of every workspace member.
export function checkClippyLists(root, workspaceDirs) {
  const errors = [];
  for (const dir of workspaceDirs) {
    if (!(dir in CRATES)) errors.push(`clippy: ${dir} is a workspace member with no tier — add it to CRATES in scripts/clippy-denylist.mjs (sim, strict or permissive), then ${FIX}`);
  }
  for (const [dir, tier] of Object.entries(CRATES)) {
    const file = clippyPath(root, dir);
    const marker = markerFor(dir);
    const shown = `${dir}/clippy.toml`;
    if (!existsSync(path.join(root, dir))) continue; // only games/vigil can be absent (Lore-only game)
    if (dir !== TEMPLATE_DIR && !workspaceDirs.includes(dir)) {
      errors.push(`clippy: CRATES lists ${dir}, which is not a workspace member — remove it from scripts/clippy-denylist.mjs`);
      continue;
    }
    if (!existsSync(file)) { errors.push(`clippy: ${shown} is missing (tier ${tier}) — create it with a header comment, then ${FIX}`); continue; }
    const content = readLf(file);
    if (content.includes('\r')) errors.push(`clippy: ${shown} has CR line endings — the tree is LF only`);
    if (tier === 'permissive') {
      const code = content.split('\n').filter((l) => !/^\s*#/.test(l)).join('\n');
      if (/disallowed-(types|methods)/.test(code) || content.includes(MARKER) || content.includes(TEMPLATE_MARKER)) {
        errors.push(`clippy: ${shown} is permissive but carries a denylist — remove it, or move the crate to another tier in scripts/clippy-denylist.mjs`);
      }
    } else if (content.split(marker).length !== 2) {
      errors.push(`clippy: ${shown} (tier ${tier}) has no generated section — ${FIX}`);
    } else if (content !== expected(content, tier, marker)) {
      errors.push(`clippy: ${shown} differs from the ${tier} list generated by scripts/clippy-denylist.mjs — ${FIX} (edit the lists in the script, never the file)`);
    }
  }
  return { errors, count: Object.keys(CRATES).length };
}

function main() {
  const write = process.argv.includes('--write');
  if (write) {
    let n = 0;
    for (const [dir, tier] of Object.entries(CRATES)) {
      if (tier === 'permissive') continue;
      if (!existsSync(path.join(REPO_ROOT, dir))) continue; // only games/vigil can be absent (Lore-only game)
      const file = clippyPath(REPO_ROOT, dir);
      if (!existsSync(file)) { console.error(`clippy-denylist: ${dir}/clippy.toml is missing — create it with a header comment first`); process.exit(1); }
      const content = readLf(file);
      const next = expected(content, tier, markerFor(dir));
      if (next !== content) { writeFileAtomic(file, next); n++; }
    }
    console.log(`clippy-denylist: wrote ${n} file(s)`);
    return;
  }
  const { errors, count } = checkClippyLists(REPO_ROOT, workspaceDirs(REPO_ROOT));
  if (errors.length === 0) { console.log(`clippy-denylist: OK (${count} clippy.toml files in step)`); return; }
  console.error(`clippy-denylist: ${errors.length} problem(s)`);
  for (const e of errors) console.error(`  - ${e}`);
  process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
