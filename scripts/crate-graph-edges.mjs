#!/usr/bin/env node
// The crate-graph edge listing, generated from `cargo metadata`. The
// block between the markers in `dev-docs/crate-graph-edges.md` used to be hand-kept and had drifted
// from the manifests (ten missing crates, wrong feature gates). Now it is derived: in-workspace edges
// with the feature that turns each optional one on, the third-party stacks, and the confinement rows.
// `--no-deps` metadata names only workspace members, so the output is the same on every OS and
// without the Lore-only game (vigil is an excluded workspace).
//
// Usage:  node scripts/crate-graph-edges.mjs            report drift (exit 1 on any)
//         node scripts/crate-graph-edges.mjs --write    regenerate the block (check.mjs --fix runs it too)
//
// `scripts/lists-in-step.mjs` imports `checkCrateGraph`, so `check.mjs` and CI run the same check.
// Zero npm dependencies — Node built-ins only.

import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { writeFileAtomic } from './atomic-write.mjs';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EDGES_DOC = 'dev-docs/crate-graph-edges.md';
const GRAPH_DOC = 'dev-docs/crate-graph.md';

export const BEGIN = '<!-- generated by scripts/crate-graph-edges.mjs; regenerate with: node scripts/crate-graph-edges.mjs --write -->';
export const END = '<!-- end generated -->';
const FIX = 'run `node scripts/crate-graph-edges.mjs --write` (or check.mjs --fix)';

const STACKS = ['wgpu', 'tokio', 'winit', 'gilrs', 'notify', 'ludion-rapier3d', 'saphyr-parser'];
const NAME_WIDTH = 22;
const WRAP = 100;
const CONT = ' '.repeat(6);
const byteSort = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const short = (n) => n.replace(/^ludion-/, '');

// The features of `pkg` that switch `dep` on (`dep:x`, `x`, or `x/...`), sorted.
function enablers(pkg, dep) {
  const out = [];
  for (const [feat, values] of Object.entries(pkg.features ?? {})) {
    if (values.some((v) => v === `dep:${dep}` || v === dep || v.startsWith(`${dep}/`))) out.push(feat);
  }
  return out.sort(byteSort);
}

function label(pkg, dep, inWorkspace) {
  let s = inWorkspace ? short(dep.name) : dep.name;
  if (inWorkspace && dep.features?.length) s += `{${[...dep.features].sort(byteSort).join(',')}}`;
  if (dep.optional) {
    const feats = enablers(pkg, dep.name);
    if (feats.length) s += `(${feats.join('|')})`;
  }
  if (dep.target) s += `<${dep.target}>`;
  return s;
}

function wrap(prefix, text) {
  const parts = text.split(', ');
  const lines = [];
  let line = prefix;
  let first = true;
  for (const part of parts) {
    const piece = first ? part : `, ${part}`;
    if (!first && line.length + piece.length > WRAP) {
      lines.push(`${line},`);
      line = CONT + part;
    } else {
      line += piece;
    }
    first = false;
  }
  lines.push(line);
  return lines;
}

// Splits a package's `kind` dependencies into in-workspace and third-party label lists, sorted.
function split(pkg, kind, names) {
  const inWs = [];
  const third = [];
  for (const dep of pkg.dependencies.filter((d) => (d.kind ?? 'normal') === kind)) {
    const ws = names.has(dep.name);
    (ws ? inWs : third).push({ key: dep.name, text: label(pkg, dep, ws) });
  }
  const sorted = (xs) => xs.sort((a, b) => byteSort(a.key, b.key)).map((x) => x.text);
  return { inWs: sorted(inWs), third: sorted(third) };
}

function row(prefix, parts) {
  const ws = parts.inWs.length ? parts.inWs.join(', ') : '(none)';
  const text = parts.third.length ? `${ws}  [${parts.third.join(', ')}]` : ws;
  return wrap(prefix, text);
}

export function renderEdges(metadata) {
  const pkgs = [...metadata.packages].sort((a, b) => byteSort(a.name, b.name));
  const names = new Set(pkgs.map((p) => p.name));
  const lines = [];
  for (const pkg of pkgs) {
    lines.push(...row(`${pkg.name.padEnd(NAME_WIDTH)} → `, split(pkg, 'normal', names)));
    for (const kind of ['dev', 'build']) {
      const parts = split(pkg, kind, names);
      if (parts.inWs.length + parts.third.length === 0) continue;
      lines.push(...row(`    ${kind}: `, parts));
    }
  }

  // Confinement rows: normal + optional edges only.
  lines.push('');
  const normal = (pkg) => pkg.dependencies.filter((d) => (d.kind ?? 'normal') === 'normal');
  const width = Math.max(...STACKS.map((s) => s.length), ...pkgs.flatMap((p) => normal(p)
    .filter((d) => names.has(d.name) && d.features?.length)
    .flatMap((d) => d.features.map((f) => `${short(d.name)}/${f}`.length))));
  const pad = (s) => s.padEnd(width);
  for (const stack of STACKS) {
    const users = [];
    for (const pkg of pkgs) {
      const dep = normal(pkg).find((d) => d.name === stack);
      if (!dep) continue;
      const feats = dep.optional ? enablers(pkg, dep.name) : [];
      users.push(feats.length ? `${short(pkg.name)}(${feats.join('|')})` : short(pkg.name));
    }
    lines.push(...wrap(`${pad(stack)} ← `, users.join(', ')));
  }
  const featRows = new Map();
  for (const pkg of pkgs) {
    for (const dep of normal(pkg)) {
      if (!names.has(dep.name)) continue;
      for (const f of dep.features ?? []) {
        const key = `${short(dep.name)}/${f}`;
        const users = featRows.get(key) ?? [];
        const spelled = dep.optional ? `${short(pkg.name)}(${enablers(pkg, dep.name).join('|')})` : short(pkg.name);
        users.push(spelled);
        featRows.set(key, users);
      }
    }
  }
  for (const key of [...featRows.keys()].sort(byteSort)) {
    lines.push(...wrap(`${pad(key)} ← `, featRows.get(key).join(', ')));
  }

  // Crates from which no normal/optional in-workspace path reaches a direct wgpu dependency.
  const direct = new Set(pkgs.filter((p) => normal(p).some((d) => d.name === 'wgpu')).map((p) => p.name));
  const memo = new Map();
  const byName = new Map(pkgs.map((p) => [p.name, p]));
  const reaches = (name, seen = new Set()) => {
    if (memo.has(name)) return memo.get(name);
    if (direct.has(name)) return true;
    if (seen.has(name)) return false;
    seen.add(name);
    const hit = normal(byName.get(name)).some((d) => names.has(d.name) && reaches(d.name, seen));
    memo.set(name, hit);
    return hit;
  };
  const free = pkgs.filter((p) => !reaches(p.name)).map((p) => short(p.name));
  lines.push('');
  lines.push(...wrap('no wgpu in the tree: ', free.join(', ')));
  return `\`\`\`\n${lines.join('\n')}\n\`\`\``;
}

// Replaces the region between the markers with `generated` (already fenced).
export function spliceEdges(docText, generated) {
  const b = docText.indexOf(BEGIN);
  const e = docText.indexOf(END);
  if (b < 0) throw new Error(`crate-graph: ${EDGES_DOC} has no line \`${BEGIN}\``);
  if (e < 0) throw new Error(`crate-graph: ${EDGES_DOC} has no line \`${END}\``);
  if (e < b) throw new Error(`crate-graph: the end marker comes before the begin marker in ${EDGES_DOC}`);
  return `${docText.slice(0, b + BEGIN.length)}\n${generated}\n${docText.slice(e)}`;
}

// The vendored physics forks are members only so `cargo package` verifies them with their dependents;
// the graph lists them as the third-party stack they are.
const isVendored = (pkg) => pkg.manifest_path.replaceAll('\\', '/').includes('/vendor/');

function loadMetadata(root) {
  try {
    const metadata = JSON.parse(execFileSync('cargo', ['metadata', '--no-deps', '--offline', '--format-version', '1'], {
      cwd: root, encoding: 'utf8', maxBuffer: 64 << 20, stdio: ['ignore', 'pipe', 'pipe'],
    }));
    return { ...metadata, packages: metadata.packages.filter((p) => !isVendored(p)) };
  } catch (err) {
    const stderr = (err.stderr ?? '').toString().trim();
    return { error: `cargo metadata failed: ${stderr || err.message}` };
  }
}

const readLf = (p) => readFileSync(p, 'utf8').replace(/\r\n/g, '\n');

export function checkCrateGraph(root) {
  const errors = [];
  const metadata = loadMetadata(root);
  if (metadata.error) return { errors: [`crate-graph: ${metadata.error}`], count: 0 };
  const edges = readLf(path.join(root, EDGES_DOC));
  const b = edges.indexOf(BEGIN);
  const e = edges.indexOf(END);
  if (b < 0 || e < b) {
    errors.push(`crate-graph: ${EDGES_DOC} is missing its generated-region markers (\`${BEGIN}\` … \`${END}\`), each on its own line`);
  } else if (spliceEdges(edges, renderEdges(metadata)) !== edges) {
    errors.push(`crate-graph: the generated block in ${EDGES_DOC} differs from the manifests — ${FIX}`);
  }
  const graph = readLf(path.join(root, GRAPH_DOC));
  for (const pkg of metadata.packages) {
    const dir = path.relative(root, path.dirname(pkg.manifest_path)).split(path.sep).join('/');
    if (!graph.includes(`\`${dir}/\``)) errors.push(`crate-graph: ${dir} has no entry in ${GRAPH_DOC}, add one line under Layout`);
  }
  return { errors, count: metadata.packages.length };
}

function main() {
  if (process.argv.includes('--write')) {
    const metadata = loadMetadata(REPO_ROOT);
    if (metadata.error) { console.error(`crate-graph-edges: ${metadata.error}`); process.exit(1); }
    const file = path.join(REPO_ROOT, EDGES_DOC);
    const text = readLf(file);
    const next = spliceEdges(text, renderEdges(metadata));
    if (next !== text) writeFileAtomic(file, next);
    console.log(`crate-graph-edges: ${next !== text ? 'wrote' : 'unchanged'} ${EDGES_DOC}`);
    return;
  }
  const { errors, count } = checkCrateGraph(REPO_ROOT);
  if (errors.length === 0) { console.log(`crate-graph-edges: OK (${count} packages in step)`); return; }
  console.error(`crate-graph-edges: ${errors.length} problem(s)`);
  for (const err of errors) console.error(`  - ${err}`);
  process.exit(1);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
